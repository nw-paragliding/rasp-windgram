import pytest

from rasp.lattice import LambertConformal, fine_mass_points, lattice_placement
from rasp.namelist_generator import (_parse_simple_yaml, compute_nest_chain,
                                     generate_namelist_input, generate_namelist_wps,
                                     load_domain_config)

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = Path(__file__).resolve().parent / "golden"

LATTICE = {"truelat1": 46.0, "truelat2": 49.0, "stand_lon": -120.5,
           "ref_lat": 47.5, "ref_lon": -120.5}

# The seven production Washington tiles.
TILES = {
    "issaquah": (47.22, -121.80),
    "wenatchee": (47.22, -120.59),
    "skykomish": (48.03, -121.80),
    "chelan": (48.03, -120.59),
    "baker": (48.84, -121.80),
    "methow": (48.84, -120.59),
    "waterville": (47.72, -119.45),
}


def _write_tile(tmp_path, name, lat, lon, lattice=True):
    lines = [f"name: {name}", "model: nam", f"center_lat: {lat}",
             f"center_lon: {lon}", "outer_dx_km: 4.0", "target_dx_km: 1.33",
             "inner_extent_km: 120", "nest_ratio: 3", "e_vert: 52"]
    if lattice:
        lines.append("lattice:")
        lines += [f"  {k}: {v}" for k, v in LATTICE.items()]
    p = tmp_path / f"{name}.yaml"
    p.write_text("\n".join(lines) + "\n")
    return p


