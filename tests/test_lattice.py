@pytest.fixture(scope="module")
def tiles(tmp_path_factory):
    tmp = tmp_path_factory.mktemp("tiles")
    out = {}
    for name, (lat, lon) in TILES.items():
        config = load_domain_config(_write_tile(tmp, name, lat, lon))
        domains = compute_nest_chain(config)
        lp = lattice_placement(config, domains)
        out[name] = (config, domains, lp)
    return out


def test_tile_chain_shape(tiles):
    for config, domains, lp in tiles.values():
        assert [d["dx"] for d in domains] == pytest.approx([4000.0, 4000.0 / 3])
        assert (domains[1]["e_we"] - 1) % 3 == 0
        assert isinstance(lp["ref_x"], int) and isinstance(lp["ref_y"], int)


def test_snapped_center_within_half_dx(tiles):
    for name, (config, domains, lp) in tiles.items():
        dx = domains[0]["dx"]
        sx, sy = lp["center_shift_m"]
        assert abs(sx) <= dx / 2 + 1e-6 and abs(sy) <= dx / 2 + 1e-6, name
        # The snapped centre really is where the shift says.
        proj = lp["projection"]
        x0, y0 = proj.forward(config["center_lat"], config["center_lon"])
        x1, y1 = proj.forward(*lp["snapped_center"])
        assert (x1 - x0, y1 - y0) == pytest.approx((sx, sy), abs=1e-4)


def test_origin_is_a_mass_point_of_every_level(tiles):
    for config, domains, lp in tiles.values():
        xs, ys = fine_mass_points(lp, domains)
        fdx = domains[-1]["dx"]
        # Fine mass point k sits at xs[0] + (k-1)*fdx; the origin (x = 0) is at
        # k = 1 - xs[0]/fdx, which may lie outside the tile.
        assert lp["origin_ij"][-1] == (round(1 - xs[0] / fdx), round(1 - ys[0] / fdx))
        assert all(abs(x / fdx - round(x / fdx)) < 1e-6 for x in xs)
        assert all(abs(y / fdx - round(y / fdx)) < 1e-6 for y in ys)
        assert lp["fine_offset"][0] == round(xs[0] / fdx)
        assert lp["fine_offset"][1] == round(ys[0] / fdx)


def _overlap(a, b):
    return max(a[0], b[0]), min(a[-1], b[-1])


def test_neighbouring_tiles_share_fine_mass_points(tiles):
    names = list(tiles)
    fdx = 4000.0 / 3
    pairs = 0
    for a, b in itertools.combinations(names, 2):
        _, da, la = tiles[a]
        _, db, lb = tiles[b]
        xa, ya = fine_mass_points(la, da)
        xb, yb = fine_mass_points(lb, db)
        lo_x, hi_x = _overlap(xa, xb)
        lo_y, hi_y = _overlap(ya, yb)
        if lo_x > hi_x or lo_y > hi_y:
            continue                      # not neighbours: no overlap
        pairs += 1
        # Offset between the two lattices is an integer number of fine cells...
        off_x = (xa[0] - xb[0]) / fdx
        off_y = (ya[0] - yb[0]) / fdx
        assert abs(off_x - round(off_x)) < 1e-6, (a, b, off_x)
        assert abs(off_y - round(off_y)) < 1e-6, (a, b, off_y)
        # ...so every point of A inside the overlap is also a point of B.
        sb_x = {round(x / fdx) for x in xb}
        sb_y = {round(y / fdx) for y in yb}
        in_x = [x for x in xa if lo_x <= x <= hi_x]
        in_y = [y for y in ya if lo_y <= y <= hi_y]
        assert in_x and in_y
        for x in in_x:
            assert round(x / fdx) in sb_x and min(abs(x - v) for v in xb) < 1e-6
        for y in in_y:
            assert round(y / fdx) in sb_y and min(abs(y - v) for v in yb) < 1e-6
        # lat/lon of a shared point agree when computed from each tile
        pa = la["projection"].inverse(in_x[0], in_y[0])
        pb = lb["projection"].inverse(in_x[0], in_y[0])
        assert pa == pytest.approx(pb, abs=1e-9)
    # The column neighbours (N-S and E-W) all overlap, plus waterville.
    assert pairs >= 9


def test_tiles_without_lattice_do_not_align(tmp_path):
    """Sanity: the old centre-based grids really are misaligned."""
    a = load_domain_config(_write_tile(tmp_path, "issaquah", *TILES["issaquah"], lattice=False))
    b = load_domain_config(_write_tile(tmp_path, "wenatchee", *TILES["wenatchee"], lattice=False))
    assert a["center_lon"] != b["center_lon"]   # different stand_lon -> different projections
    assert "lattice" not in a


def test_namelist_wps_lattice_lines(tiles, tmp_path):
    config, domains, lp = tiles["issaquah"]
    wps = generate_namelist_wps(config, domains, "2026-04-06", "00")
    assert " ref_lat  = 47.500000,\n" in wps
    assert " ref_lon  = -120.500000,\n" in wps
    assert f" ref_x    = {lp['ref_x']}.0,\n" in wps
    assert f" ref_y    = {lp['ref_y']}.0,\n" in wps
    assert " truelat1 = 46.000000,\n truelat2 = 49.000000,\n stand_lon = -120.500000,\n" in wps
    # namelist.input carries no projection: identical with or without lattice
    plain = dict(config)
    plain.pop("lattice")
    assert (generate_namelist_input(config, domains, "2026-04-06", "00")
            == generate_namelist_input(plain, domains, "2026-04-06", "00"))


def test_lattice_validation(tmp_path):
    p = _write_tile(tmp_path, "x", 47.22, -121.8)
    p.write_text(p.read_text().replace("  ref_lon: -120.5\n", ""))
    with pytest.raises(ValueError, match="missing"):
        load_domain_config(p)
    p.write_text(p.read_text() + "  ref_lon: -120.5\n  truelat3: 1\n")
    with pytest.raises(ValueError, match="unknown"):
        load_domain_config(p)
    q = _write_tile(tmp_path, "y", 47.22, -121.8)
    q.write_text(q.read_text().replace("nest_ratio: 3", "nest_ratio: 2"))
    with pytest.raises(ValueError, match="odd"):
        load_domain_config(q)


def test_simple_yaml_fallback_parses_nested_blocks():
    text = (ROOT / "examples/cascades.yaml").read_text() + "lattice:\n" + "".join(
        f"  {k}: {v}  # c\n" for k, v in LATTICE.items())
    cfg = _parse_simple_yaml(text)
    assert cfg["lattice"] == LATTICE
    assert cfg["physics"]["bl_pbl_physics"] == 1
    assert cfg["e_vert"] == 52 and "truelat1" not in cfg
