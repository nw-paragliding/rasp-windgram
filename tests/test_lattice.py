GOLDEN_CONFIGS = sorted(ROOT.glob("examples/*.yaml")) + [ROOT / "ab/phoenix.yaml"]


@pytest.mark.parametrize("cfg", GOLDEN_CONFIGS, ids=lambda p: f"{p.parent.name}/{p.name}")
def test_namelists_without_lattice_are_byte_identical(cfg):
    """Golden files were generated by the 0.6.1 generator (origin/main 498cf79)."""
    config = load_domain_config(cfg)
    assert "lattice" not in config
    domains = compute_nest_chain(config)
    stem = f"{cfg.parent.name}-{cfg.stem}"
    wps = generate_namelist_wps(config, domains, "2026-04-06", "00")
    nml = generate_namelist_input(config, domains, "2026-04-06", "00")
    assert wps == (GOLDEN / f"{stem}.namelist.wps").read_text()
    assert nml == (GOLDEN / f"{stem}.namelist.input").read_text()


def test_required_goldens_present():
    for stem in ("examples-cascades", "ab-phoenix"):
        assert (GOLDEN / f"{stem}.namelist.wps").exists()
        assert (GOLDEN / f"{stem}.namelist.input").exists()


