def test_lambert_roundtrip_and_origin():
    proj = LambertConformal(46.0, 49.0, -120.5, 47.5, -120.5)
    assert proj.forward(47.5, -120.5) == pytest.approx((0.0, 0.0), abs=1e-6)
    for lat, lon in TILES.values():
        x, y = proj.forward(lat, lon)
        assert proj.inverse(x, y) == pytest.approx((lat, lon), abs=1e-10)
    # Scale is true on the standard parallels: 1 deg of longitude along 46N.
    x1, _ = proj.forward(46.0, -121.0)
    x2, _ = proj.forward(46.0, -120.0)
    chord = 2 * 6370000.0 * math.cos(math.radians(46.0)) * math.sin(math.radians(0.5))
    assert abs(x2 - x1) == pytest.approx(chord, rel=1e-4)


def test_lambert_matches_pyproj():
    pyproj = pytest.importorskip("pyproj")
    crs = pyproj.CRS.from_dict({"proj": "lcc", "lat_1": 46.0, "lat_2": 49.0,
                                "lat_0": 47.5, "lon_0": -120.5, "R": 6370000.0})
    t = pyproj.Transformer.from_crs("EPSG:4326", crs, always_xy=True)
    proj = LambertConformal(46.0, 49.0, -120.5, 47.5, -120.5)
    for lat, lon in TILES.values():
        assert proj.forward(lat, lon) == pytest.approx(t.transform(lon, lat), abs=1e-3)


